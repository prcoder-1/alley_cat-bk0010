#pragma once
#include <stdint.h>

/*
 * Аппаратный слой: время, ввод, динамик.
 *
 * Время: оригинал считает тики BIOS (int 1Ah, 18,2 Гц) и местами — проходы
 * главного цикла (~85 за тик на PC 4,77 МГц, замер re/calib.py). Здесь оба
 * счёта ведутся от свободно бегущего таймера БК, поэтому скорость игры не
 * зависит от быстродействия БК.
 */

/** Текущий тик (аналог DX после int 1Ah AH=0) */
uint16_t ticks(void);

/** Сколько «проходов главного цикла PC» прошло с прошлого вызова (1 и больше) */
uint16_t loop_passes(void);

/** Подождать смены тика */
void wait_tick(void);

void hw_init(void);

/*
 * Ввод в терминах оригинала: состояния клавиш таблицы DS:06B7 (0 = нажата,
 * 0x80 = отпущена). Индексы совпадают с таблицей скан-кодов DS:06A1.
 */
enum KEY_IDX
{
    K_ALT, K_UP, K_RIGHT, K_DOWN, K_LEFT, K_PGUP, K_PGDN, K_END, K_HOME,
    K_ESC, K_Y, K_N, K_K, K_H, K_T, K_A, K_S, K_R, K_CTRL, K_DEL, K_M, K_9,
    K_COUNT
};

extern uint8_t key_state[K_COUNT];  /* DS:06B7 */
extern uint16_t key_presses;        /* DS:0693 — счётчик нажатий */

/** Опросить клавиатуру и джойстик, обновить key_state */
void input_poll(void);
uint8_t key_code(void);    /* последняя нажатая клавиша (заглавная) */
uint16_t joy_button(void); /* кнопка джойстика нажата (не 0) */

/** Динамик: включить/выключить уровень (бит 6 регистра 0177716) */
void spk_set(uint8_t on);

/** Аналог 0x13D8 (порт 3DAh, бит 3): идёт ли кадровый обратный ход CGA.
 *  Виртуальный сигнал: период 1/60 с, доля 8% (как в re/pcemu.py). */
uint8_t retrace(void);

/** Обновить счёт тиков; вернуть отсчёты таймера (23437,5 Гц) с прошлого вызова */
uint16_t tmr_elapsed(void);
/** Восстановить счётчик тиков (пауза: время стоит) */
void ticks_set(uint16_t t);
